                    case 'nama_pembimbing':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->pembimbingSekolah?->nama_lengkap ?: 'Belum Diplot');
                        break;
                    case 'mentor_dudi':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->pembimbingDudi?->nama_lengkap ?: ($siswa->pembimbing_dudi_nama ?: '-'));
                        break;
