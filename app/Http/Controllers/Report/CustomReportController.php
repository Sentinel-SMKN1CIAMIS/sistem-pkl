    /**
     * Membangun sheet rekap kehadiran dan jurnal siswa.
     */
    protected function buildKehadiranReport($sheet, array $selectedColumns, Spreadsheet $spreadsheet, bool $includePivot, array $filters)
    {
        $allColumnDefs = [
            'nama_siswa' => 'Nama Siswa',
            'nis' => 'NIS',
            'kelas' => 'Kelas',
            'jurusan' => 'Jurusan',
            'nama_dudi' => 'Tempat PKL',
            'total_hadir' => 'Total Hadir',
            'sakit' => 'Sakit (S)',
            'izin' => 'Izin (I)',
            'alpa' => 'Alpa / Tanpa Keterangan (A)',
            'persentase_kehadiran' => 'Persentase Kehadiran (%)',
            'total_jurnal_valid' => 'Total Jurnal Valid',
        ];

        $columns = array_intersect(array_keys($allColumnDefs), $selectedColumns);
        if (empty($columns)) {
            $columns = ['nama_siswa', 'nis', 'kelas', 'jurusan', 'nama_dudi', 'total_hadir', 'sakit', 'izin', 'alpa', 'persentase_kehadiran', 'total_jurnal_valid'];
        }

        $headers = array_merge(['No'], array_map(fn($c) => $allColumnDefs[$c], $columns));
        $this->renderHeaders($sheet, $headers);

        $query = Siswa::with(['konsentrasiKeahlian', 'dudi', 'absensis', 'jurnals'])
            ->orderBy('kelas')
            ->orderBy('nama_lengkap');

        if (!empty($filters['filter_jurusan'])) {
            $query->whereHas('konsentrasiKeahlian', function ($q) use ($filters) {
                $q->whereIn('kode', (array) $filters['filter_jurusan']);
            });
        }
        if (!empty($filters['filter_kelas']) && $filters['filter_kelas'] !== 'all') {
            $query->where('kelas', $filters['filter_kelas']);
        }

        $siswas = $query->get();
        $rowIdx = 2;

        foreach ($siswas as $idx => $siswa) {
            $hadir = $siswa->absensis->where('status', 'hadir')->count();
            $sakit = $siswa->absensis->where('status', 'sakit')->count();
            $izin = $siswa->absensis->where('status', 'izin')->count();
            $alpa = $siswa->absensis->where('status', 'alpa')->count();
            $totalAbsen = $hadir + $sakit + $izin + $alpa;
            $persentase = $totalAbsen > 0 ? round(($hadir / $totalAbsen) * 100, 1) : 0;
            $jurnalValid = $siswa->jurnals->where('status', 'valid')->count();

            $sheet->setCellValue('A' . $rowIdx, $idx + 1);

            $colIdx = 2;
            foreach ($columns as $colKey) {
                $colLetter = Coordinate::stringFromColumnIndex($colIdx);
                switch ($colKey) {
                    case 'nama_siswa':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->nama_lengkap);
                        break;
                    case 'nis':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $siswa->nis ?: '-', DataType::TYPE_STRING);
                        break;
                    case 'kelas':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->kelas ?: '-');
                        break;
                    case 'jurusan':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->konsentrasiKeahlian?->nama ?: '-');
                        break;
                    case 'nama_dudi':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->dudi?->nama ?: 'Belum Diplot');
                        break;
                    case 'total_hadir':
                        $sheet->setCellValue($colLetter . $rowIdx, $hadir);
                        break;
                    case 'sakit':
                        $sheet->setCellValue($colLetter . $rowIdx, $sakit);
                        break;
                    case 'izin':
                        $sheet->setCellValue($colLetter . $rowIdx, $izin);
                        break;
                    case 'alpa':
                        $sheet->setCellValue($colLetter . $rowIdx, $alpa);
                        break;
                    case 'persentase_kehadiran':
                        $sheet->setCellValue($colLetter . $rowIdx, $persentase . '%');
                        break;
                    case 'total_jurnal_valid':
                        $sheet->setCellValue($colLetter . $rowIdx, $jurnalValid);
                        break;
                }
                $colIdx++;
            }
            $rowIdx++;
        }

        $this->styleDataSheet($sheet, count($headers), $rowIdx - 1);
    }

    /**
     * Memeriksa apakah password siswa masih berupa password default (NIS / NISN).
     */
    protected function isSiswaPasswordDefault(Siswa $siswa): bool
    {
        if (!$siswa->user) {
            return true;
        }

        if ($siswa->user->force_password_change) {
            return true;
        }

        if (!empty($siswa->nis) && Hash::check($siswa->nis, $siswa->user->password)) {
            return true;
        }

        if (!empty($siswa->nisn) && Hash::check($siswa->nisn, $siswa->user->password)) {
            return true;
        }

        return false;
    }

    /**
     * Memeriksa apakah password guru masih berupa password default ('smkn1ciamis').
     */
    protected function isGuruPasswordDefault(PembimbingSekolah $guru): bool
    {
        if (!$guru->user) {
            return true;
        }

        if ($guru->user->force_password_change) {
            return true;
        }

        if (Hash::check('smkn1ciamis', $guru->user->password)) {
            return true;
        }

        return false;
    }

    /**
     * Helper untuk render baris header dengan gaya elegan.
     */
    protected function renderHeaders($sheet, array $headers, string $headerColor = '1E293B')
    {
        foreach ($headers as $colIdx => $title) {
            $colLetter = Coordinate::stringFromColumnIndex($colIdx + 1);
            $sheet->setCellValue($colLetter . '1', $title);
        }

        $totalCols = count($headers);
        $lastCol = Coordinate::stringFromColumnIndex($totalCols);

        $sheet->getStyle('A1:' . $lastCol . '1')->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF'], 'size' => 11],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => $headerColor]],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
            ],
        ]);
        $sheet->getRowDimension('1')->setRowHeight(28);
    }

    /**
     * Helper untuk auto-size kolom dan border tabel.
     */
    protected function styleDataSheet($sheet, int $totalCols, int $totalRows)
    {
        $lastCol = Coordinate::stringFromColumnIndex($totalCols);

        // Auto width
        for ($c = 1; $c <= $totalCols; $c++) {
            $sheet->getColumnDimension(Coordinate::stringFromColumnIndex($c))->setAutoSize(true);
        }

        if ($totalRows >= 2) {
            $sheet->getStyle('A1:' . $lastCol . $totalRows)->applyFromArray([
                'borders' => [
                    'allBorders' => [
                        'borderStyle' => Border::BORDER_THIN,
                        'color' => ['rgb' => 'E2E8F0'],
                    ],
                ],
                'alignment' => [
                    'vertical' => Alignment::VERTICAL_CENTER,
                ],
            ]);

            // Center align for No column
            $sheet->getStyle('A2:A' . $totalRows)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
        }
    }
