    /**
     * Export custom report ke file Excel (.xlsx) atau CSV dengan streaming.
     */
    public function export(Request $request)
    {
        $module = $request->input('module', 'kredensial_siswa');
        $selectedColumns = $request->input('columns', []);
        $format = strtolower($request->input('format', 'xlsx'));
        $includePivot = (bool) $request->input('include_pivot', true);

        // Filters
        $filterJurusan = $request->input('filter_jurusan', []);
        $filterKelas = $request->input('filter_kelas');
        $filterPasswordStatus = $request->input('filter_password_status', 'all');
        $filterStatusPkl = $request->input('filter_status_pkl', 'all');
        $filterTahunAjaran = $request->input('filter_tahun_ajaran');

        if (empty($selectedColumns) || !is_array($selectedColumns)) {
            return back()->with('error', 'Silakan pilih minimal 1 kolom data untuk diekspor.');
        }

        $spreadsheet = new Spreadsheet();
        $spreadsheet->getProperties()
            ->setCreator('SMK Negeri 1 Ciamis - Sistem MAS-PKL')
            ->setTitle('Custom Report ' . ucfirst(str_replace('_', ' ', $module)))
            ->setDescription('Generated by Custom Dynamic Report & Automated Excel/Pivot Builder');

        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle('Data Mentah');

        // Build data based on module
        switch ($module) {
            case 'kredensial_guru':
                $this->buildGuruReport($sheet, $selectedColumns, $spreadsheet, $includePivot, [
                    'filter_password_status' => $filterPasswordStatus,
                ]);
                $filename = 'data-akun-pembimbing-sekolah-' . now()->format('Ymd-His');
                break;

            case 'penempatan_pkl':
                $this->buildPenempatanReport($sheet, $selectedColumns, $spreadsheet, $includePivot, [
                    'filter_jurusan' => $filterJurusan,
                    'filter_kelas' => $filterKelas,
                    'filter_status_pkl' => $filterStatusPkl,
                    'filter_tahun_ajaran' => $filterTahunAjaran,
                ]);
                $filename = 'rekap-penempatan-pkl-' . now()->format('Ymd-His');
                break;

            case 'kehadiran_siswa':
                $this->buildKehadiranReport($sheet, $selectedColumns, $spreadsheet, $includePivot, [
                    'filter_jurusan' => $filterJurusan,
                    'filter_kelas' => $filterKelas,
                    'filter_tahun_ajaran' => $filterTahunAjaran,
                ]);
                $filename = 'rekap-kehadiran-siswa-pkl-' . now()->format('Ymd-His');
                break;

            case 'kredensial_siswa':
            default:
                $this->buildSiswaReport($sheet, $selectedColumns, $spreadsheet, $includePivot, [
                    'filter_jurusan' => $filterJurusan,
                    'filter_kelas' => $filterKelas,
                    'filter_password_status' => $filterPasswordStatus,
                    'filter_status_pkl' => $filterStatusPkl,
                    'filter_tahun_ajaran' => $filterTahunAjaran,
                ]);
                $filename = 'data-akun-kredensial-siswa-angkatan-' . now()->format('Ymd-His');
                break;
        }

        $spreadsheet->setActiveSheetIndex(0);

        if ($format === 'csv') {
            $writer = new Csv($spreadsheet);
            $contentType = 'text/csv';
            $filename .= '.csv';
        } else {
            $writer = new Xlsx($spreadsheet);
            $contentType = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
            $filename .= '.xlsx';
        }

        return response()->stream(
            function () use ($writer) {
                $writer->save('php://output');
            },
            200,
            [
                'Content-Type' => $contentType,
                'Content-Disposition' => "attachment; filename=\"{$filename}\"",
                'Cache-Control' => 'max-age=0',
            ]
        );
    }

    /**
     * Membangun sheet data siswa (kredensial dan akun).
     */
    protected function buildSiswaReport($sheet, array $selectedColumns, Spreadsheet $spreadsheet, bool $includePivot, array $filters)
    {
        $allColumnDefs = [
            'nama_siswa' => 'Nama Siswa',
            'nis' => 'NIS',
            'nisn' => 'NISN',
            'kelas' => 'Kelas',
            'jurusan' => 'Program / Konsentrasi',
            'username' => 'Username Akun',
            'password_default' => 'Password Awal (Default)',
            'status_password' => 'Status Keamanan Password',
            'nama_dudi' => 'Tempat DU/DI (PKL)',
            'pembimbing_sekolah' => 'Guru Pembimbing Sekolah',
            'status_pkl' => 'Status PKL',
            'no_hp' => 'No. HP Siswa',
        ];

        $columns = array_intersect(array_keys($allColumnDefs), $selectedColumns);
        if (empty($columns)) {
            $columns = ['nama_siswa', 'nis', 'kelas', 'jurusan', 'username', 'password_default', 'status_password', 'nama_dudi', 'pembimbing_sekolah'];
        }

        // Render Headers
        $headers = array_merge(['No'], array_map(fn($c) => $allColumnDefs[$c], $columns));
        $this->renderHeaders($sheet, $headers);

        // Fetch query
        $query = Siswa::with(['user', 'konsentrasiKeahlian.programKeahlian', 'dudi', 'pembimbingSekolah'])
            ->orderBy('kelas')
            ->orderBy('nama_lengkap');

        if (!empty($filters['filter_jurusan'])) {
            $query->whereHas('konsentrasiKeahlian', function ($q) use ($filters) {
                $q->whereIn('kode', (array) $filters['filter_jurusan'])
                  ->orWhereHas('programKeahlian', function ($pq) use ($filters) {
                      $pq->whereIn('kode', (array) $filters['filter_jurusan']);
                  });
            });
        }

        if (!empty($filters['filter_kelas']) && $filters['filter_kelas'] !== 'all') {
            $query->where('kelas', $filters['filter_kelas']);
        }

        if (!empty($filters['filter_status_pkl']) && $filters['filter_status_pkl'] !== 'all') {
            $query->where('status_pkl', $filters['filter_status_pkl']);
        }

        if (!empty($filters['filter_tahun_ajaran']) && $filters['filter_tahun_ajaran'] !== 'all') {
            $query->where('tahun_ajaran', $filters['filter_tahun_ajaran']);
        }

        $siswas = $query->get();

        // Filter password status in memory if specified
        if (!empty($filters['filter_password_status']) && $filters['filter_password_status'] !== 'all') {
            $siswas = $siswas->filter(function ($siswa) use ($filters) {
                $isDefault = $this->isSiswaPasswordDefault($siswa);
                return $filters['filter_password_status'] === 'default' ? $isDefault : !$isDefault;
            });
        }

        $rowIdx = 2;
        $pivotSummary = [];

        foreach ($siswas as $idx => $siswa) {
            $isDefault = $this->isSiswaPasswordDefault($siswa);
            $jurusanName = $siswa->konsentrasiKeahlian?->kode ?: ($siswa->konsentrasiKeahlian?->programKeahlian?->kode ?: 'Umum');

            // Collect aggregation for pivot
            if (!isset($pivotSummary[$jurusanName])) {
                $pivotSummary[$jurusanName] = [
                    'jurusan' => $jurusanName,
                    'total' => 0,
                    'mapped' => 0,
                    'unmapped' => 0,
                    'default_pwd' => 0,
                    'changed_pwd' => 0,
                ];
            }
            $pivotSummary[$jurusanName]['total']++;
            if ($siswa->dudi_id) {
                $pivotSummary[$jurusanName]['mapped']++;
            } else {
                $pivotSummary[$jurusanName]['unmapped']++;
            }
            if ($isDefault) {
                $pivotSummary[$jurusanName]['default_pwd']++;
            } else {
                $pivotSummary[$jurusanName]['changed_pwd']++;
            }

            // Fill row
            $sheet->setCellValue('A' . $rowIdx, $idx + 1);

            $colIdx = 2;
            foreach ($columns as $colKey) {
                $colLetter = Coordinate::stringFromColumnIndex($colIdx);
                switch ($colKey) {
                    case 'nama_siswa':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->nama_lengkap);
                        break;
                    case 'nis':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $siswa->nis ?: '-', DataType::TYPE_STRING);
                        break;
                    case 'nisn':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $siswa->nisn ?: '-', DataType::TYPE_STRING);
                        break;
                    case 'kelas':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->kelas ?: '-');
                        break;
                    case 'jurusan':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->konsentrasiKeahlian?->nama ?: $jurusanName);
                        break;
                    case 'username':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $siswa->user?->username ?: $siswa->nis, DataType::TYPE_STRING);
                        break;
                    case 'password_default':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $siswa->nis ?: '12345678', DataType::TYPE_STRING);
                        break;
                    case 'status_password':
                        $sheet->setCellValue($colLetter . $rowIdx, $isDefault ? 'Default (Wajib Ubah)' : 'Sudah Diubah Siswa');
                        break;
                    case 'nama_dudi':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->dudi?->nama ?: 'Belum Diplot');
                        break;
                    case 'pembimbing_sekolah':
                        $sheet->setCellValue($colLetter . $rowIdx, $siswa->pembimbingSekolah?->nama_lengkap ?: 'Belum Diplot');
                        break;
                    case 'status_pkl':
                        $sheet->setCellValue($colLetter . $rowIdx, ucwords(str_replace('_', ' ', $siswa->status_pkl ?: 'belum_mulai')));
                        break;
                    case 'no_hp':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $siswa->no_hp ?: '-', DataType::TYPE_STRING);
                        break;
                }
                $colIdx++;
            }
            $rowIdx++;
        }

        $this->styleDataSheet($sheet, count($headers), $rowIdx - 1);

        // Build Sheet 2: Pivot / Rekapitulasi Otomatis
        if ($includePivot) {
            $pivotSheet = $spreadsheet->createSheet();
            $pivotSheet->setTitle('Rekapitulasi & Pivot');

            $pivotHeaders = ['No', 'Program / Jurusan', 'Total Siswa', 'Sudah Diplot DUDI', 'Belum Diplot DUDI', 'Password Masih Default', 'Password Sudah Diubah'];
            $this->renderHeaders($pivotSheet, $pivotHeaders, '0F766E'); // Teal header

            $pRow = 2;
            $n = 1;
            $sumTotal = 0; $sumMapped = 0; $sumUnmapped = 0; $sumDef = 0; $sumChg = 0;

            foreach ($pivotSummary as $p) {
                $pivotSheet->setCellValue('A' . $pRow, $n++);
                $pivotSheet->setCellValue('B' . $pRow, $p['jurusan']);
                $pivotSheet->setCellValue('C' . $pRow, $p['total']);
                $pivotSheet->setCellValue('D' . $pRow, $p['mapped']);
                $pivotSheet->setCellValue('E' . $pRow, $p['unmapped']);
                $pivotSheet->setCellValue('F' . $pRow, $p['default_pwd']);
                $pivotSheet->setCellValue('G' . $pRow, $p['changed_pwd']);

                $sumTotal += $p['total'];
                $sumMapped += $p['mapped'];
                $sumUnmapped += $p['unmapped'];
                $sumDef += $p['default_pwd'];
                $sumChg += $p['changed_pwd'];
                $pRow++;
            }

            // Total row
            $pivotSheet->setCellValue('A' . $pRow, '');
            $pivotSheet->setCellValue('B' . $pRow, 'TOTAL KESELURUHAN');
            $pivotSheet->setCellValue('C' . $pRow, $sumTotal);
            $pivotSheet->setCellValue('D' . $pRow, $sumMapped);
            $pivotSheet->setCellValue('E' . $pRow, $sumUnmapped);
            $pivotSheet->setCellValue('F' . $pRow, $sumDef);
            $pivotSheet->setCellValue('G' . $pRow, $sumChg);

            $pivotSheet->getStyle('A' . $pRow . ':G' . $pRow)->applyFromArray([
                'font' => ['bold' => true],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'F1F5F9']],
            ]);

            $this->styleDataSheet($pivotSheet, count($pivotHeaders), $pRow);
        }
    }

    /**
     * Membangun sheet data akun guru pembimbing sekolah.
     */
    protected function buildGuruReport($sheet, array $selectedColumns, Spreadsheet $spreadsheet, bool $includePivot, array $filters)
    {
        $allColumnDefs = [
            'nama_guru' => 'Nama Guru Pembimbing',
            'nip' => 'NIP',
            'username' => 'Username Akun',
            'password_default' => 'Password Awal (Default)',
            'status_password' => 'Status Keamanan Password',
            'email' => 'Email Akun',
            'tipe_guru' => 'Tipe Pembimbing',
            'jumlah_bimbingan' => 'Jumlah Siswa Bimbingan',
            'daftar_dudi' => 'Tempat DUDI Bimbingan',
            'no_hp' => 'No. HP / Kontak',
        ];

        $columns = array_intersect(array_keys($allColumnDefs), $selectedColumns);
        if (empty($columns)) {
            $columns = ['nama_guru', 'nip', 'username', 'password_default', 'status_password', 'email', 'tipe_guru', 'jumlah_bimbingan', 'daftar_dudi'];
        }

        $headers = array_merge(['No'], array_map(fn($c) => $allColumnDefs[$c], $columns));
        $this->renderHeaders($sheet, $headers);

        $gurus = PembimbingSekolah::with(['user', 'siswa.dudi'])
            ->withCount('siswa')
            ->orderBy('nama_lengkap')
            ->get();

        if (!empty($filters['filter_password_status']) && $filters['filter_password_status'] !== 'all') {
            $gurus = $gurus->filter(function ($guru) use ($filters) {
                $isDefault = $this->isGuruPasswordDefault($guru);
                return $filters['filter_password_status'] === 'default' ? $isDefault : !$isDefault;
            });
        }

        $rowIdx = 2;
        $pivotSummary = [
            'kejuruan' => ['tipe' => 'Kejuruan', 'guru' => 0, 'siswa' => 0],
            'umum' => ['tipe' => 'Umum', 'guru' => 0, 'siswa' => 0],
        ];

        foreach ($gurus as $idx => $guru) {
            $isDefault = $this->isGuruPasswordDefault($guru);
            $tipeKey = strtolower($guru->tipe ?: 'kejuruan');
            if (!isset($pivotSummary[$tipeKey])) {
                $pivotSummary[$tipeKey] = ['tipe' => ucfirst($tipeKey), 'guru' => 0, 'siswa' => 0];
            }
            $pivotSummary[$tipeKey]['guru']++;
            $pivotSummary[$tipeKey]['siswa'] += $guru->siswa_count;

            $dudiNames = $guru->siswa->pluck('dudi.nama')->filter()->unique()->implode(', ');

            $sheet->setCellValue('A' . $rowIdx, $idx + 1);

            $colIdx = 2;
            foreach ($columns as $colKey) {
                $colLetter = Coordinate::stringFromColumnIndex($colIdx);
                switch ($colKey) {
                    case 'nama_guru':
                        $sheet->setCellValue($colLetter . $rowIdx, $guru->nama_lengkap);
                        break;
                    case 'nip':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $guru->nip ?: '-', DataType::TYPE_STRING);
                        break;
                    case 'username':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $guru->user?->username ?: '-', DataType::TYPE_STRING);
                        break;
                    case 'password_default':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, 'smkn1ciamis', DataType::TYPE_STRING);
                        break;
                    case 'status_password':
                        $sheet->setCellValue($colLetter . $rowIdx, $isDefault ? 'Default (smkn1ciamis)' : 'Sudah Diubah Guru');
                        break;
                    case 'email':
                        $sheet->setCellValue($colLetter . $rowIdx, $guru->user?->email ?: '-');
                        break;
                    case 'tipe_guru':
                        $sheet->setCellValue($colLetter . $rowIdx, ucfirst($guru->tipe ?: 'Kejuruan'));
                        break;
                    case 'jumlah_bimbingan':
                        $sheet->setCellValue($colLetter . $rowIdx, $guru->siswa_count . ' Siswa');
                        break;
                    case 'daftar_dudi':
                        $sheet->setCellValue($colLetter . $rowIdx, $dudiNames ?: 'Belum ada bimbingan');
                        break;
                    case 'no_hp':
                        $sheet->setCellValueExplicit($colLetter . $rowIdx, $guru->no_hp ?: '-', DataType::TYPE_STRING);
                        break;
                }
                $colIdx++;
            }
            $rowIdx++;
        }

        $this->styleDataSheet($sheet, count($headers), $rowIdx - 1);

        if ($includePivot) {
            $pivotSheet = $spreadsheet->createSheet();
            $pivotSheet->setTitle('Rekapitulasi & Pivot');

            $pivotHeaders = ['No', 'Tipe Pembimbing', 'Total Guru', 'Total Siswa Dibimbing', 'Rata-rata Siswa per Guru'];
            $this->renderHeaders($pivotSheet, $pivotHeaders, '1E3A8A');

            $pRow = 2;
            $n = 1;
            $totG = 0; $totS = 0;

            foreach ($pivotSummary as $p) {
                $avg = $p['guru'] > 0 ? round($p['siswa'] / $p['guru'], 1) : 0;
                $pivotSheet->setCellValue('A' . $pRow, $n++);
                $pivotSheet->setCellValue('B' . $pRow, $p['tipe']);
                $pivotSheet->setCellValue('C' . $pRow, $p['guru']);
                $pivotSheet->setCellValue('D' . $pRow, $p['siswa']);
                $pivotSheet->setCellValue('E' . $pRow, $avg . ' Siswa');

                $totG += $p['guru'];
                $totS += $p['siswa'];
                $pRow++;
            }

            $overallAvg = $totG > 0 ? round($totS / $totG, 1) : 0;
            $pivotSheet->setCellValue('A' . $pRow, '');
            $pivotSheet->setCellValue('B' . $pRow, 'TOTAL KESELURUHAN');
            $pivotSheet->setCellValue('C' . $pRow, $totG);
            $pivotSheet->setCellValue('D' . $pRow, $totS);
            $pivotSheet->setCellValue('E' . $pRow, $overallAvg . ' Siswa');

            $pivotSheet->getStyle('A' . $pRow . ':E' . $pRow)->applyFromArray([
                'font' => ['bold' => true],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'F1F5F9']],
            ]);

            $this->styleDataSheet($pivotSheet, count($pivotHeaders), $pRow);
        }
    }

